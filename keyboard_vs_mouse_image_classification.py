##Step 6 - Creating dataset
"""

#use TensorFlow's image_dataset_from_directory.
import os
import shutil

base_dir = "CNN_Project"

combined_dir = "CNN_Project/combined_dataset"

keyboard_combined = os.path.join(combined_dir, "Keyboard")
mouse_combined = os.path.join(combined_dir, "Mouse")

os.makedirs(keyboard_combined, exist_ok=True)
os.makedirs(mouse_combined, exist_ok=True)

#copy keyboard images
for filename in os.listdir(keyboard_path):

    source = os.path.join(keyboard_path, filename)
    destination = os.path.join(keyboard_combined, filename)

    if os.path.isfile(source):
        shutil.copy2(source, destination)

#copy mouse images
for filename in os.listdir(mouse_path):

    source = os.path.join(mouse_path, filename)
    destination = os.path.join(mouse_combined, filename)

    if os.path.isfile(source):
        shutil.copy2(source, destination)

print("Keyboard:", len(os.listdir(keyboard_combined)))
print("Mouse:", len(os.listdir(mouse_combined)))

"""##Step 7 - Load dataset  using tensorflow"""

import tensorflow as tf

print("TensorFlow version:", tf.__version__)

#Set parameters
IMG_SIZE = (128, 128)
BATCH_SIZE = 32
SEED = 42

#Load training dataset
train_ds = tf.keras.utils.image_dataset_from_directory(
    combined_dir,
    validation_split=0.30,
    subset="training",
    seed=SEED,
    image_size=IMG_SIZE,
    batch_size=BATCH_SIZE
)

#Load test dataset
val_test_ds = tf.keras.utils.image_dataset_from_directory(
    combined_dir,
    validation_split=0.30,
    subset="validation",
    seed=SEED,
    image_size=IMG_SIZE,
    batch_size=BATCH_SIZE
)

class_names = train_ds.class_names

print(class_names)

"""##Step 8 - Create validation and tests dataset"""

# currently we have
# 70% Training
# 30% Validation + Test

# We will split that 30% into
# 15% Validation
# 15% Test

#Calculate the no. of batches
val_test_batches = tf.data.experimental.cardinality(val_test_ds)

print("Validation/Test batches:", val_test_batches)

#Split
test_batches = val_test_batches // 2

test_ds = val_test_ds.take(test_batches)
val_ds = val_test_ds.skip(test_batches)

#now
# Training → 70%
# Validation → 15%
# Testing → 15%

"""##Step 9 - Visual training images"""

plt.figure(figsize=(10, 10))

for images, labels in train_ds.take(1):

    for i in range(9):

        ax = plt.subplot(3, 3, i + 1)
        plt.imshow(images[i].numpy().astype("uint8"))
        plt.title(class_names[labels[i]])
        plt.axis("off")

plt.tight_layout()
plt.show()

"""##Step 10 - improve dataset performance"""

#using tensorflow prefetching
AUTOTUNE = tf.data.AUTOTUNE

train_ds = train_ds.prefetch(buffer_size=AUTOTUNE)
val_ds = val_ds.prefetch(buffer_size=AUTOTUNE)
test_ds = test_ds.prefetch(buffer_size=AUTOTUNE)

"""##Step 11 - add data agumentation"""

data_augmentation = tf.keras.Sequential([
    tf.keras.layers.RandomFlip("horizontal"),
    tf.keras.layers.RandomRotation(0.1),
    tf.keras.layers.RandomZoom(0.1)
])

#Visualization
plt.figure(figsize=(10, 10))

for images, labels in train_ds.take(1):

    first_image = images[0]

    for i in range(9):

        augmented_image = data_augmentation(
            tf.expand_dims(first_image, 0)
        )

        ax = plt.subplot(3, 3, i + 1)
        plt.imshow(
            augmented_image[0].numpy().astype("uint8")
        )
        plt.axis("off")

plt.tight_layout()
plt.show()

"""##Step 12 - Build the CNN"""

model = tf.keras.Sequential([

    # Data augmentation
    data_augmentation,

    # Normalize pixels
    tf.keras.layers.Rescaling(1./255),

    # CNN Layer 1
    tf.keras.layers.Conv2D(
        32,
        (3, 3),
        activation="relu"
    ),
    tf.keras.layers.MaxPooling2D(),

    # CNN Layer 2
    tf.keras.layers.Conv2D(
        64,
        (3, 3),
        activation="relu"
    ),
    tf.keras.layers.MaxPooling2D(),

    # CNN Layer 3
    tf.keras.layers.Conv2D(
        128,
        (3, 3),
        activation="relu"
    ),
    tf.keras.layers.MaxPooling2D(),

    # Convert feature maps to vector
    tf.keras.layers.Flatten(),

    # Fully connected layer
    tf.keras.layers.Dense(
        128,
        activation="relu"
    ),

    # Prevent overfitting
    tf.keras.layers.Dropout(0.5),

    # Binary classification
    tf.keras.layers.Dense(
        1,
        activation="sigmoid"
    )
])

"""##Step 13 - View model architecture"""

model.summary()

"""##Step 14 - model compilation"""

model.compile(
    optimizer="adam",
    loss="binary_crossentropy",
    metrics=["accuracy"]
)

"""##Step 15 - Training CNN model"""

EPOCHS = 15

history = model.fit(
    train_ds,
    validation_data=val_ds,
    epochs=EPOCHS
)

"""##Step 16 - Plot training accuracy"""

plt.figure(figsize=(8, 5))

plt.plot(
    history.history["accuracy"],
    label="Training Accuracy"
)

plt.plot(
    history.history["val_accuracy"],
    label="Validation Accuracy"
)

plt.xlabel("Epoch")
plt.ylabel("Accuracy")
plt.title("Training vs Validation Accuracy")
plt.legend()
plt.grid()

plt.show()

"""##Step 17 - Plot training loss"""

plt.figure(figsize=(8, 5))

plt.plot(
    history.history["loss"],
    label="Training Loss"
)

plt.plot(
    history.history["val_loss"],
    label="Validation Loss"
)

plt.xlabel("Epoch")
plt.ylabel("Loss")
plt.title("Training vs Validation Loss")
plt.legend()
plt.grid()

plt.show()

#These two above graphs are important for explaining whether our model is underfitting or overfitting.

"""##Step 18 - Evaluate on test data"""

test_loss, test_accuracy = model.evaluate(val_test_ds)

print("Test Loss:", test_loss)
print("Test Accuracy:", test_accuracy)

# Test Loss: 1.9270061254501343
