image_array = tf.expand_dims(image_array, 0)  # Add batch dimension

# Make prediction
prediction = model.predict(image_array)
probability = prediction[0][0]

# Map predictions (0: Keyboard, 1: Mouse)
if probability >= 0.5:
    predicted_class = "Mouse"
    confidence = probability
else:
    predicted_class = "Keyboard"
    confidence = 1 - probability

# Display result
plt.imshow(image)
plt.axis("off")
plt.title(f"{predicted_class} ({confidence * 100:.2f}%)")
plt.show()

print("Prediction:", predicted_class)
print(f"Confidence: {confidence * 100:.2f}%")

plt.imshow(image)
plt.title(
    f"{predicted_class} - "
    f"{confidence * 100:.2f}%"
)
